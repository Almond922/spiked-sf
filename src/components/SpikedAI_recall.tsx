const initDB = (): Promise<IDBDatabase> => {
  return new Promise((resolve, reject) => {
    const request = indexedDB.open(DB_NAME, DB_VERSION);

    request.onerror = () => reject(request.error);
    request.onsuccess = () => resolve(request.result);

    request.onupgradeneeded = (event) => {
      const db = (event.target as IDBOpenDBRequest).result;

      if (!db.objectStoreNames.contains(TRANSCRIPTS_STORE)) {
        db.createObjectStore(TRANSCRIPTS_STORE, { keyPath: "meetingId" });
      }

      if (!db.objectStoreNames.contains(QA_HISTORY_STORE)) {
        db.createObjectStore(QA_HISTORY_STORE, {
          keyPath: "id",
          autoIncrement: true,
        });
      }
    };
  });
};

const saveToIndexedDB = async (storeName: string, data: any, key?: string) => {
  try {
    const db = await initDB();
    const transaction = db.transaction([storeName], "readwrite");
    const store = transaction.objectStore(storeName);

    if (key) {
      store.put({ ...data, meetingId: key });
    } else {
      store.add(data);
    }
  } catch (error) {
    console.error("Error saving to IndexedDB:", error);
  }
};

const loadFromIndexedDB = async (
  storeName: string,
  key?: string
): Promise<any> => {
  try {
    const db = await initDB();
    const transaction = db.transaction([storeName], "readonly");
    const store = transaction.objectStore(storeName);

    if (key) {
      const request = store.get(key);
      return new Promise((resolve) => {
        request.onsuccess = () => resolve(request.result);
        request.onerror = () => resolve(null);
      });
    } else {
      const request = store.getAll();
      return new Promise((resolve) => {
        request.onsuccess = () => resolve(request.result);
        request.onerror = () => resolve([]);
      });
    }
  } catch (error) {
    console.error("Error loading from IndexedDB:", error);
    return key ? null : [];
  }
};

const extractGoogleMeetId = (url: string): string | null => {
  try {
    const parsedUrl = new URL(url);
    if (parsedUrl.hostname === "meet.google.com") {
      const pathParts = parsedUrl.pathname.split("/").filter((part) => part);
      if (pathParts.length > 0) {
        return pathParts[0];
      }
    }
    return null;
  } catch (e) {
    return null;
  }
};

